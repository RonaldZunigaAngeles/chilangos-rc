const visitAliases: Record<string, string[]> = {
  "Real del Monte": ["Mineral del Monte"],
  Bernal: ["Peña de Bernal"],
};

const normalize = (value: string) => value
  .normalize("NFD")
  .replace(/[\u0300-\u036f]/g, "")
  .toLocaleLowerCase("es-MX");

export const visitedPueblos = pueblosMagicos.filter((town) => {
  const candidates = [town.name, ...(visitAliases[town.name] ?? [])].map(normalize);
  return rides.some((ride) => candidates.some((candidate) => normalize(ride.destination).includes(candidate)));
});

export const visitedTownNames = new Set(visitedPueblos.map((town) => town.name));

export const visitedStates = new Set(
  rides.flatMap((ride) => ride.state.split(" y ").map((state) => state.trim())),
);

export const pueblosByState = allMexicanStates
  .map((state) => {
    const towns = pueblosMagicos.filter((town) => town.state === state);
    return {
      state,
      towns,
      visitedCount: towns.filter((town) => visitedTownNames.has(town.name)).length,
      center: stateCenters[state],
    };
  });

